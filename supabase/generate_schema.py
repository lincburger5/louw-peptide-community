"""Generate the first Postgres schema from the version 4 SQLite schema.

Run once when reviewing this migration; the checked-in SQL is the source of truth.
"""
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from db import SCHEMA

sql = SCHEMA.replace('PRAGMA foreign_keys = ON;\n', '')
sql = re.sub(r'(?<![\w])id INTEGER PRIMARY KEY', 'id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', sql)
sql = sql.replace(' COLLATE NOCASE', '')
sql = sql.replace('avatar TEXT', 'avatar BIGINT')
sql = sql.replace('created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP', 'created_at TIMESTAMPTZ NOT NULL DEFAULT now()')
sql = sql.replace('updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP', 'updated_at TIMESTAMPTZ NOT NULL DEFAULT now()')
sql = sql.replace('dismissed_at TEXT', 'dismissed_at TIMESTAMPTZ')
sql = sql.replace('read_at TEXT', 'read_at TIMESTAMPTZ')
sql = re.sub(r'\bINTEGER\b', 'BIGINT', sql)
tables = re.findall(r'CREATE TABLE IF NOT EXISTS (\w+)', sql)
sql = 'CREATE SCHEMA IF NOT EXISTS forum;\nSET search_path TO forum, public;\n\n' + sql
sql += '\nCREATE UNIQUE INDEX IF NOT EXISTS users_username_ci ON users (lower(username));\n'
sql += 'CREATE TABLE IF NOT EXISTS forum.media_bytes (media_id BIGINT PRIMARY KEY REFERENCES forum.media(id) ON DELETE CASCADE, content BYTEA NOT NULL);\n'
tables.append('media_bytes')
sql += '\n'.join(f'ALTER TABLE forum.{table} ENABLE ROW LEVEL SECURITY;' for table in tables)
sql += '\nREVOKE ALL ON SCHEMA forum FROM PUBLIC, anon, authenticated;\n'
sql += 'REVOKE ALL ON ALL TABLES IN SCHEMA forum FROM PUBLIC, anon, authenticated;\n'
sql += 'REVOKE ALL ON ALL SEQUENCES IN SCHEMA forum FROM PUBLIC, anon, authenticated;\n'
sql += 'ALTER DEFAULT PRIVILEGES IN SCHEMA forum REVOKE ALL ON TABLES FROM PUBLIC, anon, authenticated;\n'
sql += 'ALTER DEFAULT PRIVILEGES IN SCHEMA forum REVOKE ALL ON SEQUENCES FROM PUBLIC, anon, authenticated;\n'
Path(__file__).with_name('001_forum_schema.sql').write_text(sql, encoding='utf-8')
