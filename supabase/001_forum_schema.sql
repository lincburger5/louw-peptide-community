CREATE SCHEMA IF NOT EXISTS forum;
SET search_path TO forum, public;


CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, username TEXT NOT NULL UNIQUE,
 password_hash TEXT NOT NULL, bio TEXT NOT NULL DEFAULT '', avatar BIGINT,
 role TEXT NOT NULL DEFAULT 'member' CHECK(role IN ('member','moderator','admin')),
 tutorial_done BIGINT NOT NULL DEFAULT 0, session_version BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS user_onboarding (
 user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 dismissed_at TIMESTAMPTZ
);
CREATE TABLE IF NOT EXISTS user_appearance (
 user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
 theme TEXT NOT NULL DEFAULT 'light' CHECK(theme IN ('light','dark')),
 font TEXT NOT NULL DEFAULT 'system' CHECK(font IN ('system','readable','serif')),
 text_size TEXT NOT NULL DEFAULT 'normal' CHECK(text_size IN ('small','normal','large','extra')),
 density TEXT NOT NULL DEFAULT 'comfortable' CHECK(density IN ('comfortable','compact')),
 motion TEXT NOT NULL DEFAULT 'system' CHECK(motion IN ('system','reduced'))
);
CREATE TABLE IF NOT EXISTS tags (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name TEXT NOT NULL UNIQUE, slug TEXT NOT NULL UNIQUE,
 description TEXT NOT NULL, approved BIGINT NOT NULL DEFAULT 1,
 kind TEXT NOT NULL DEFAULT 'general'
);
CREATE TABLE IF NOT EXISTS posts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, author_id BIGINT NOT NULL REFERENCES users(id),
 type TEXT NOT NULL CHECK(type IN ('story','question','progress')),
 title TEXT NOT NULL, body TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'published'
 CHECK(status IN ('draft','published','hidden','deleted')),
 is_demo BIGINT NOT NULL DEFAULT 0, created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS post_tags (
 post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
 tag_id BIGINT NOT NULL REFERENCES tags(id), PRIMARY KEY(post_id,tag_id)
);
CREATE TABLE IF NOT EXISTS media (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, post_id BIGINT REFERENCES posts(id) ON DELETE CASCADE,
 user_id BIGINT NOT NULL REFERENCES users(id), filename TEXT NOT NULL,
 kind TEXT NOT NULL CHECK(kind IN ('avatar','post')),
 label TEXT CHECK(label IN ('Before','After','Other')),
 caption TEXT NOT NULL DEFAULT '', consent BIGINT NOT NULL DEFAULT 0,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS comments (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, post_id BIGINT NOT NULL REFERENCES posts(id),
 author_id BIGINT NOT NULL REFERENCES users(id), parent_id BIGINT REFERENCES comments(id),
 body TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'published'
 CHECK(status IN ('published','hidden','deleted')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(), updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS votes (
 user_id BIGINT NOT NULL REFERENCES users(id), target_type TEXT NOT NULL CHECK(target_type IN ('post','comment')),
 target_id BIGINT NOT NULL, value BIGINT NOT NULL CHECK(value IN (-1,1)),
 PRIMARY KEY(user_id,target_type,target_id)
);
CREATE TABLE IF NOT EXISTS reports (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, reporter_id BIGINT NOT NULL REFERENCES users(id),
 target_type TEXT NOT NULL CHECK(target_type IN ('post','comment')),
 target_id BIGINT NOT NULL, reason TEXT NOT NULL, detail TEXT NOT NULL DEFAULT '',
 status TEXT NOT NULL DEFAULT 'open' CHECK(status IN ('open','resolved')),
 created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS moderation_actions (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, actor_id BIGINT NOT NULL REFERENCES users(id),
 target_type TEXT NOT NULL, target_id BIGINT NOT NULL,
 action TEXT NOT NULL, reason TEXT NOT NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS follows (
 user_id BIGINT NOT NULL REFERENCES users(id), tag_id BIGINT NOT NULL REFERENCES tags(id),
 PRIMARY KEY(user_id,tag_id)
);
CREATE TABLE IF NOT EXISTS user_follows (
 follower_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 following_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
 CHECK(follower_id != following_id), PRIMARY KEY(follower_id,following_id)
);
CREATE TABLE IF NOT EXISTS saves (
 user_id BIGINT NOT NULL REFERENCES users(id), post_id BIGINT NOT NULL REFERENCES posts(id),
 PRIMARY KEY(user_id,post_id)
);
CREATE TABLE IF NOT EXISTS notifications (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, recipient_id BIGINT NOT NULL REFERENCES users(id),
 kind TEXT NOT NULL, message TEXT NOT NULL, url TEXT NOT NULL,
 read_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS rate_limits (
 key TEXT PRIMARY KEY, window_started BIGINT NOT NULL, hits BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_posts_feed ON posts(status,created_at DESC);
CREATE INDEX IF NOT EXISTS idx_comments_post ON comments(post_id,created_at);
CREATE INDEX IF NOT EXISTS idx_reports_status ON reports(status,created_at DESC);
CREATE INDEX IF NOT EXISTS idx_notifications_recipient ON notifications(recipient_id,created_at DESC);
CREATE INDEX IF NOT EXISTS idx_user_follows_following ON user_follows(following_id);
CREATE INDEX IF NOT EXISTS idx_post_tags_tag ON post_tags(tag_id,post_id);
CREATE INDEX IF NOT EXISTS idx_saves_user ON saves(user_id,post_id);

CREATE UNIQUE INDEX IF NOT EXISTS users_username_ci ON users (lower(username));
CREATE TABLE IF NOT EXISTS forum.media_bytes (media_id BIGINT PRIMARY KEY REFERENCES forum.media(id) ON DELETE CASCADE, content BYTEA NOT NULL);
